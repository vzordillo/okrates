//! Deterministic trajectory pins `(from * 10 + to, time.to_bits())` for stream 0 + TwoSum clock.

use okrates_core::reference::GraphRandomWalk;
use okrates_core::{IncrementalSimulation, Simulation, Step};

const SEED: u64 = 20261117;
const STEPS: usize = 30;

fn star() -> GraphRandomWalk {
    GraphRandomWalk::new(vec![
        vec![(1, 1.0), (2, 2.0), (3, 3.0), (4, 4.0), (5, 0.3)],
        vec![(0, 0.5)],
        vec![(0, 0.7)],
        vec![(0, 1.1)],
        vec![(0, 1.3)],
        vec![(0, 1.7)],
    ])
    .unwrap()
}

fn record(
    mut step: impl FnMut() -> (Step<okrates_core::reference::Hop>, f64),
) -> Vec<(usize, u64)> {
    (0..STEPS)
        .map(|_| match step() {
            (Step::Fired { event, .. }, time) => (event.from * 10 + event.to, time.to_bits()),
            (Step::Absorbed, _) => panic!("star graph unexpectedly absorbed"),
        })
        .collect()
}

#[test]
fn random_walk_direct() {
    let mut sim = Simulation::new(star(), 0, SEED);
    let got = record(|| (sim.step().unwrap(), sim.time()));
    assert_eq!(got, RANDOM_WALK_DIRECT);
}

#[test]
fn random_walk_incremental() {
    let mut sim = IncrementalSimulation::new(star(), 0, SEED).unwrap();
    let got = record(|| (sim.step().unwrap(), sim.time()));
    assert_eq!(got, RANDOM_WALK_INCREMENTAL);
}

